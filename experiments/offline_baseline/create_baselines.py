"""Generate plan files for the offline baseline experiment package.

Plans reference spec.md by SHA-256. This script computes the hash and writes
validated, ready-for-generation plans. It does NOT generate expected results;
those are hand-authored in cases.json and must never be produced by the replay
engine under test.
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
from coverage_closure.artifacts import write_json
from coverage_closure.contracts import file_digest

FOLDER = Path(__file__).resolve().parent
SPEC_HASH = file_digest(FOLDER / "spec.md")
PLANS_DIR = FOLDER / "plans"
PLANS_DIR.mkdir(parents=True, exist_ok=True)

VERSIONS = {key: "offline-baseline:no-" + key for key in
            ["dut", "testbench", "monitor", "binding", "config", "checker", "simulator", "sampling"]}
STAGES = {key: "not_run" for key in ["build", "run", "export"]}


def source(sid, locator):
    return {"id": sid, "path": "../spec.md", "sha256": SPEC_HASH, "locator": locator}


def requirement(rid, sids, text):
    return {"id": rid, "source_ids": sids, "text": text, "review_status": "reviewed"}


def rule(rid, req_id, start, ends, bound):
    return {"id": rid, "revision": 1, "requirement_id": req_id, "review_status": "reviewed",
            "blockers": [], "op": "min_interval", "start_command": start, "end_commands": ends,
            "bound_ticks": bound, "history_policy": "latest_start",
            "start_anchor": "observed_start_timestamp", "end_anchor": "observed_end_timestamp"}


def main():
    # --- single_rule ---
    single = {
        "schema_version": 1, "plan_id": "offline.single_rule", "revision": 1,
        "protocol": "offline_baseline_not_ddr5", "time_unit": "ns",
        "sources": [source("src.offline.single", "Offline baseline spec, single-rule section")],
        "requirements": [requirement("req.offline.single", ["src.offline.single"],
                                     "END follows latest START by at least 4 ns in the same scope and epoch.")],
        "rules": [rule("rel.offline.single", "req.offline.single", "START", ["END"], 4)],
    }
    write_json(PLANS_DIR / "single_rule.json", single)

    # --- dual_rule ---
    dual = {
        "schema_version": 1, "plan_id": "offline.dual_rule", "revision": 1,
        "protocol": "offline_baseline_not_ddr5", "time_unit": "ns",
        "sources": [source("src.offline.dual", "Offline baseline spec, dual-rule section")],
        "requirements": [
            requirement("req.offline.rule_a", ["src.offline.dual"],
                        "Rule A: END follows latest START by at least 4 ns."),
            requirement("req.offline.rule_b", ["src.offline.dual"],
                        "Rule B: DONE follows latest END by at least 5 ns."),
        ],
        "rules": [
            rule("rel.offline.rule_a", "req.offline.rule_a", "START", ["END"], 4),
            rule("rel.offline.rule_b", "req.offline.rule_b", "END", ["DONE"], 5),
        ],
    }
    write_json(PLANS_DIR / "dual_rule.json", dual)

    # --- self_overlap ---
    self_ovl = {
        "schema_version": 1, "plan_id": "offline.self_overlap", "revision": 1,
        "protocol": "offline_baseline_not_ddr5", "time_unit": "ns",
        "sources": [source("src.offline.self", "Offline baseline spec, self-overlap section")],
        "requirements": [requirement("req.offline.self", ["src.offline.self"],
                                     "START follows latest START by at least 4 ns; START is both start and end.")],
        "rules": [rule("rel.offline.self", "req.offline.self", "START", ["START", "END"], 4)],
    }
    write_json(PLANS_DIR / "self_overlap.json", self_ovl)

    print(f"spec.md SHA-256: {SPEC_HASH}")
    print("Plans written to experiments/offline_baseline/plans/")
    print("Expected results are hand-authored in cases.json (not generated by replay).")


if __name__ == "__main__":
    main()
